async function seedBlog() {
  try {
    await mongoose.connect(DB);
    console.log('Connected to MongoDB');

    const admin = await User.findOne({ role: 'admin' });

    let inserted = 0;
    for (const postData of posts) {
      const exists = await BlogPost.findOne({ slug: postData.slug });
      if (!exists) {
        await BlogPost.create({ ...postData, author: admin?._id });
        inserted++;
        console.log(`  Created: ${postData.title}`);
      } else {
        console.log(`  Skipped (exists): ${postData.title}`);
      }
    }

    console.log(`\nBlog seed complete. ${inserted} posts created.`);
    process.exit(0);
  } catch (err) {
    console.error('Blog seed failed:', err);
    process.exit(1);
  }
}

seedBlog();
